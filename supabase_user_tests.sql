-- Week 6: external user tests (T1 to T5). Run once in the Supabase SQL editor.
-- No names, emails or phone numbers: testers are identified by a tag like T1.
-- Row Level Security is ON. The public key may only read these rows (the dashboard
-- and /impact need that); rows are added by the owner in the SQL editor.
create table if not exists public.user_tests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  tester_tag text not null,
  finished_alone boolean,
  minutes numeric,
  baseline_minutes numeric,
  trust_1_5 int check (trust_1_5 between 1 and 5),
  quote text,
  found_bug boolean default false,
  route_tested text
);
alter table public.user_tests enable row level security;
create policy "public can read tester rows" on public.user_tests for select to anon using (true);

